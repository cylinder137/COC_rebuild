#!/usr/bin/env node
/**
 * coc-platform ops/seed : generate the traffic seed for the published demo projects
 *
 * Emits ops/seed/assets/views.generated.sql containing
 *   - project_view_daily  : the last 30 days  (per project, with realistic noise)
 *   - project_view_hourly : the last 48 hours
 *
 * Values are deterministic for a given (project, day/hour) so re-running the
 * seed never changes history, but they are always relative to "now" so the
 * charts in the UI always have fresh data.
 *
 * Usage: node gen-views.js
 */
const fs = require('fs');
const path = require('path');

// projects that are actually published (status = 2)
const PROJECTS = [
  { id: 201, base: 118, weekendBoost: 1.35 },  // html, flagship demo
  { id: 203, base: 54, weekendBoost: 1.20 },   // scratch
  { id: 204, base: 41, weekendBoost: 1.15 },   // scratch
  { id: 205, base: 26, weekendBoost: 1.10 }    // structure
];

// deterministic PRNG (mulberry32)
function rng(seed) {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const pad = (n) => String(n).padStart(2, '0');
function ymd(d) { return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`; }
function ymdh(d) { return `${ymd(d)} ${pad(d.getHours())}:00:00`; }

const now = new Date();

// ---------------------------------------------------------------- daily
const dailyRows = [];
for (const p of PROJECTS) {
  for (let back = 29; back >= 0; back--) {
    const d = new Date(now.getFullYear(), now.getMonth(), now.getDate() - back);
    const seed = p.id * 100003 + back * 7919 + d.getDate() * 31 + (d.getMonth() + 1) * 7;
    const r = rng(seed);
    const dow = d.getDay();
    const weekend = (dow === 0 || dow === 6) ? p.weekendBoost : 1;
    const trend = 1 + (29 - back) * 0.012;            // very slight growth over the month
    const wave = 1 + 0.22 * Math.sin(back / 2.7);     // 2-3 day rhythm
    let v = p.base * weekend * trend * wave * (0.62 + r() * 0.78);
    if (back === 0) v *= 0.55;                        // today is still running
    dailyRows.push(`(${p.id}, '${ymd(d)}', ${Math.max(1, Math.round(v))})`);
  }
}

// --------------------------------------------------------------- hourly
const hourlyRows = [];
for (const p of PROJECTS) {
  for (let back = 47; back >= 0; back--) {
    const h = new Date(now.getFullYear(), now.getMonth(), now.getDate(), now.getHours() - back);
    const seed = p.id * 7717 + back * 131 + h.getHours() * 17 + h.getDate() * 3;
    const r = rng(seed);
    const hour = h.getHours();
    // daytime traffic curve peaking around 20:00-22:00
    const dayCurve = 0.28 + 0.72 * Math.max(0, Math.sin(((hour - 5) / 24) * Math.PI * 1.55));
    let v = (p.base / 14) * dayCurve * (0.55 + r() * 0.95);
    if (back === 0) v *= 0.6;                          // current hour, partial
    hourlyRows.push(`(${p.id}, '${ymdh(h)}', ${Math.max(0, Math.round(v))})`);
  }
}

let sql = '-- AUTO-GENERATED by ops/seed/gen-views.js -- do not edit by hand\n';
sql += '-- generated at ' + new Date().toISOString() + '\n';
sql += 'INSERT INTO project_view_daily (project_id, stat_date, view_count) VALUES\n  ';
sql += dailyRows.join(',\n  ');
sql += '\nON DUPLICATE KEY UPDATE view_count = VALUES(view_count);\n\n';
sql += 'INSERT INTO project_view_hourly (project_id, stat_hour, view_count) VALUES\n  ';
sql += hourlyRows.join(',\n  ');
sql += '\nON DUPLICATE KEY UPDATE view_count = VALUES(view_count);\n';

const out = path.join(__dirname, 'assets', 'views.generated.sql');
fs.writeFileSync(out, sql, 'utf8');
console.log(`[gen-views] ${dailyRows.length} daily rows / ${hourlyRows.length} hourly rows -> ${out}`);
PROJECTS.forEach((p) => {
  const mine = dailyRows.filter((r) => r.startsWith('(' + p.id + ','));
  const sum = mine.reduce((a, r) => a + Number(r.match(/,\s*(\d+)\)$/)[1]), 0);
  console.log(`  - project ${p.id}: last 30 days total ${sum} views`);
});
